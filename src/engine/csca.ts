import type { FieldId, LanguageCode, Profile } from '../types'
import { L } from '../i18n/lang'

/**
 * CSCA — вступительный экзамен для иностранцев, поступающих в вузы Китая.
 *
 * Состав предметов не фиксирован: он собирается из направления и из языка,
 * на котором человек собирается учиться. На англоязычных программах
 * профессиональный китайский обычно не сдают вовсе, а физика и химия нужны
 * только профильным направлениям. Поэтому здесь не список «всех предметов»,
 * а набор под конкретную анкету, с объяснением, откуда взялся каждый.
 */

export type CscaTrack = 'zh' | 'en'

export interface CscaSubject {
  id: string
  title: string
  titleKk: string
  /** Короткое имя для перечисления в одну строку: без уточнений через запятую. */
  short: string
  shortKk: string
  /** Оригинальное название, как оно стоит в расписании экзамена. */
  original: string
  /** Почему предмет попал в набор именно у этого человека. */
  why: string
  whyKk: string
  required: boolean
}

export interface CscaPlan {
  /** Имеет ли экзамен отношение к этой анкете. */
  relevant: boolean
  /** Язык обучения, под который собран набор. */
  track: CscaTrack
  trackNote: string
  subjects: CscaSubject[]
  source: { label: string; url: string }
}

const SCIENCE_FIELDS: FieldId[] = ['engineering', 'science', 'it']
const CHEM_FIELDS: FieldId[] = ['medicine', 'agro', 'science', 'engineering']
/** Направления, где профессиональный китайский идёт в гуманитарном варианте. */
const HUMANITIES: FieldId[] = ['social', 'law', 'business', 'economics', 'media', 'education', 'design']

/**
 * Язык обучения определяется по анкете: если человек знает китайский, для него
 * открыты китаеязычные программы, где сдают профессиональный китайский.
 * Если нет — набор собирается под англоязычный поток.
 */
function trackOf(languages: LanguageCode[]): CscaTrack {
  return languages.includes('zh') ? 'zh' : 'en'
}

export function cscaPlan(profile: Profile): CscaPlan {
  const track = trackOf(profile.languages)
  const fields = profile.fields
  const subjects: CscaSubject[] = []

  subjects.push({
    id: 'math',
    title: 'Математика',
    titleKk: 'Математика',
    short: 'математика',
    shortKk: 'математика',
    original: '数学',
    why: 'Обязательна почти на всех направлениях: технических, естественно-научных, экономических и бизнесе.',
    whyKk: 'Барлық дерлік бағытта міндетті: техникалық, жаратылыстану, экономикалық және бизнесте.',
    required: true,
  })

  if (track === 'zh') {
    const humanities = fields.some((f) => HUMANITIES.includes(f))
    subjects.push({
      id: 'chinese',
      title: humanities
        ? 'Профессиональный китайский, гуманитарное направление'
        : 'Профессиональный китайский, естественно-научное направление',
      titleKk: humanities
        ? 'Кәсіби қытай тілі, гуманитарлық бағыт'
        : 'Кәсіби қытай тілі, жаратылыстану бағыты',
      short: 'профессиональный китайский',
      shortKk: 'кәсіби қытай тілі',
      original: '专业汉语',
      why: humanities
        ? 'Ты указал китайский среди своих языков, а направление гуманитарное — значит сдаётся гуманитарный вариант профессионального китайского.'
        : 'Ты указал китайский среди своих языков, а направление естественно-научное — значит сдаётся научный вариант профессионального китайского.',
      whyKk: humanities
        ? 'Тілдеріңнің арасында қытай тілін көрсеттің, бағытың гуманитарлық — демек кәсіби қытай тілінің гуманитарлық нұсқасы тапсырылады.'
        : 'Тілдеріңнің арасында қытай тілін көрсеттің, бағытың жаратылыстану — демек кәсіби қытай тілінің ғылыми нұсқасы тапсырылады.',
      required: true,
    })
  }

  if (fields.some((f) => SCIENCE_FIELDS.includes(f))) {
    subjects.push({
      id: 'physics',
      title: 'Физика',
      titleKk: 'Физика',
      short: 'физика',
      shortKk: 'физика',
      original: '物理',
      why: 'Профильный предмет по выбору: обязателен для технических, инженерных и физико-научных направлений.',
      whyKk: 'Таңдау бойынша бейіндік пән: техникалық, инженерлік және физика-ғылыми бағыттарға міндетті.',
      required: true,
    })
  }

  if (fields.some((f) => CHEM_FIELDS.includes(f))) {
    subjects.push({
      id: 'chemistry',
      title: 'Химия',
      titleKk: 'Химия',
      short: 'химия',
      shortKk: 'химия',
      original: '化学',
      why: 'Профильный предмет по выбору: нужен для инженерии, медицины, естественных и аграрных наук.',
      whyKk: 'Таңдау бойынша бейіндік пән: инженерия, медицина, жаратылыстану және аграрлық ғылымдарға қажет.',
      required: true,
    })
  }

  const trackNote = track === 'zh'
    ? L(
        'Набор собран под обучение на китайском: в нём есть профессиональный китайский. Если выберешь англоязычную программу, этот предмет уйдёт.',
        'Жинақ қытай тілінде оқуға құрылған: онда кәсіби қытай тілі бар. Ағылшын тілді бағдарламаны таңдасаң, бұл пән алынады.',
      )
    : L(
        'Набор собран под англоязычные программы: на них профессиональный китайский обычно не сдают. Добавь китайский в список своих языков, и предмет появится.',
        'Жинақ ағылшын тілді бағдарламаларға құрылған: оларда кәсіби қытай тілі әдетте тапсырылмайды. Тілдер тізіміне қытай тілін қоссаң, пән пайда болады.',
      )

  return {
    relevant: profile.countries.includes('CN'),
    track,
    trackNote,
    subjects,
    source: { label: 'campuschina.org', url: 'https://www.campuschina.org' },
  }
}
