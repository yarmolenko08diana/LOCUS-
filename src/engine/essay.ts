export interface EssayReview {
  doc: EssayDoc
  /** Готовность документа, 0–100. */
  readiness: number
  /** Словами: на какой стадии текст. */
  verdict: string
  /** Требования, которые ещё не закрыты, по убыванию важности. */
  todo: EssayCriterion[]
  /** Насколько этот документ важен для текущей подборки. */
  importance: 'high' | 'medium' | 'low'
  importanceNote: string
}

const STATE_VALUE: Record<CriterionState, number> = { yes: 1, partly: 0.5, no: 0 }

/**
 * Насколько документ важен именно этому человеку.
 *
 * Если в рекомендациях преобладают вузы, которые читают заявку целиком,
 * эссе весит больше, чем ещё один балл ЕНТ. Если в топе только программы
 * с приёмом по баллам, честнее сказать об этом прямо.
 */
function importanceOf(
  doc: EssayDocId, profile: Profile, recs: Recommendation[],
): { level: EssayReview['importance']; note: string } {
  const top = recs.slice(0, 8)
  if (top.length === 0) {
    return {
      level: 'medium',
      note: L('Заполни анкету, и мы посчитаем, насколько этот документ важен для твоей подборки.',
        'Сауалнаманы толтыр, сонда бұл құжаттың сенің тізіміңе қаншалықты маңызды екенін есептейміз.'),
    }
  }
  if (doc === 'motivation') {
    const holistic = top.filter((r) => r.program.holistic >= 4).length
    if (holistic >= 3) {
      return {
        level: 'high',
        note: L(`В твоём топе ${holistic} из ${top.length} программ читают заявку целиком: эссе здесь весит не меньше баллов.`,
          `Сенің үздігіңде ${top.length} бағдарламаның ${holistic}-і өтінімді тұтас оқиды: мұнда эссе баллдан кем түспейді.`),
      }
    }
    if (holistic >= 1) {
      return {
        level: 'medium',
        note: L(`Часть программ в топе (${holistic} из ${top.length}) смотрит на заявку целиком — эссе им понадобится.`,
          `Үздіктегі бағдарламалардың бір бөлігі (${top.length}-тің ${holistic}-і) өтінімді тұтас қарайды — оларға эссе керек болады.`),
      }
    }
    return {
      level: 'low',
      note: L('В твоём текущем топе решают баллы, а не текст. Эссе всё равно пригодится для стипендий.',
        'Қазіргі үздігіңде мәтін емес, баллдар шешеді. Эссе шәкіртақыға бәрібір керек болады.'),
    }
  }
  const grantCountries = new Set(['KR', 'JP', 'CN', 'HU', 'TR'])
  const hits = top.filter((r) => grantCountries.has(r.program.country)).length
  if (hits >= 2 || profile.budget === 'grant-only') {
    return {
      level: 'high',
      note: L('Ты метишь в грантовые программы, а там study plan обычно обязателен.',
        'Сен гранттық бағдарламаларды мақсат етіп отырсың, ал онда study plan әдетте міндетті.'),
    }
  }
  if (hits === 1) {
    return {
      level: 'medium',
      note: L('Одна программа из топа просит study plan — лучше подготовить заранее.',
        'Үздіктегі бір бағдарлама study plan сұрайды — алдын ала дайындаған дұрыс.'),
    }
  }
  return {
    level: 'low',
    note: L('Для твоей нынешней подборки study plan скорее запасной документ.',
      'Қазіргі тізіміңе study plan көбіне қосалқы құжат.'),
  }
}

export function reviewEssays(
  profile: Profile,
  recs: Recommendation[],
  answers: Partial<Record<string, CriterionState>>,
): EssayReview[] {
  return essayDocs().map((doc) => {
    const total = doc.criteria.reduce((sum, c) => sum + c.weight, 0)
    const got = doc.criteria.reduce(
      (sum, c) => sum + c.weight * STATE_VALUE[answers[c.id] ?? 'no'], 0,
    )
    const readiness = Math.round((got / total) * 100)
    const todo = doc.criteria
      .filter((c) => (answers[c.id] ?? 'no') !== 'yes')
      .sort((a, b) => b.weight - a.weight)
    const answered = doc.criteria.filter((c) => answers[c.id]).length
    const { level, note } = importanceOf(doc.id, profile, recs)

    let verdict: string
    if (answered === 0) {
      verdict = L('Отметь пункты, и мы покажем, что в тексте уже сделано, а что осталось.',
        'Тармақтарды белгіле, сонда мәтінде не істелгенін, не қалғанын көрсетеміз.')
    } else if (readiness >= 85) {
      verdict = L('Текст закрывает основные требования. Остались детали и вычитка.',
        'Мәтін негізгі талаптарды жабады. Бөлшектер мен түзету қалды.')
    } else if (readiness >= 55) {
      verdict = L('Основа есть, но по паре пунктов текст пока проседает.',
        'Негізі бар, бірақ бірер тармақ бойынша мәтін әзірге ақсап тұр.')
    } else if (readiness >= 25) {
      verdict = L('Черновик начат. Самое важное ещё не закрыто — с этого и начни.',
        'Жоба басталды. Ең маңыздысы әлі жабылмаған — содан баста.')
    } else {
      verdict = L('Текста по сути ещё нет. Возьми первый пункт списка и напиши абзац сегодня.',
        'Мәтін әлі жоқ деуге болады. Тізімнің бірінші тармағын алып, бүгін бір абзац жаз.')
    }

    return { doc, readiness, verdict, todo, importance: level, importanceNote: note }
  })
}
