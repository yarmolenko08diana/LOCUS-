/**
 * Разбор мотивационного эссе и study plan.
 *
 * Эссе — единственная часть заявки, которую человек пишет сам, и единственная,
 * по которой нельзя посмотреть проходной балл. Поэтому здесь не оценка текста,
 * а разбор по требованиям: что приёмная комиссия ищет в таком тексте, что из
 * этого уже закрыто и что осталось. Никакой «вероятности поступления» это не
 * даёт и не заменяет чтение живым человеком.
 */

export type EssayDocId = 'motivation' | 'studyPlan'

/** Ответ на пункт требований: закрыто, частично или нет. */
export type CriterionState = 'yes' | 'partly' | 'no'

export interface EssayCriterion {
  id: string
  doc: EssayDocId
  /** Само требование, одной строкой. */
  title: string
  titleKk: string
  /** Почему это требование существует. */
  why: string
  whyKk: string
  /** Что сделать, если пункт не закрыт. */
  fix: string
  fixKk: string
  /** Вес пункта: у части требований цена ошибки выше. */
  weight: number
}

