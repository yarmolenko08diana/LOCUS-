import { L } from '../i18n/lang'

/**
 * Голос продукта — наставник: спокойно объясняет, почему именно так.
 *
 * Раньше стиль общения выбирал пользователь, но выбор ничего не менял
 * по сути: тон влияет только на формулировки и никогда — на то, какие
 * программы рекомендованы и как оценены шансы. Лишний шаг в анкете
 * ради этого не нужен, поэтому голос один.
 */

/** Обращение в начале разбора. */
export function greet(name: string): string {
  const who = name.trim()
  if (!who) return L('Разберём профиль по порядку.', 'Профильді ретімен талдайық.')
  return L(`${who}, разберём твой профиль по порядку.`, `${who}, профиліңді ретімен талдайық.`)
}

/** Подводка к следующему действию на экране плана. */
export function nudge(): string {
  return L('Логичный следующий шаг', 'Логикалық келесі қадам')
}

/** Комментарий к полноте анкеты. */
export function readinessPhrase(readiness: number): string {
  if (readiness >= 85) {
    return L(
      'Профиль заполнен подробно, поэтому расчёт опирается на полный набор данных.',
      'Профиль толық толтырылған, сондықтан есеп толық деректерге сүйенеді.',
    )
  }
  if (readiness >= 60) {
    return L(
      'Данных достаточно для первого приближения. Баллы экзаменов сделают оценку точнее.',
      'Дерек алғашқы жуықтауға жеткілікті. Емтихан балдары бағаны дәлдей түседі.',
    )
  }
  return L(
    'Данных мало, и это видно по точности: вернись в анкету и уточни экзамены и предметы.',
    'Дерек аз, бұл дәлдіктен көрініп тұр: сауалнамаға оралып, емтихандар мен пәндерді нақтыла.',
  )
}
