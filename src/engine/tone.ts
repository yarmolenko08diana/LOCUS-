import type { ToneId } from '../types'
import { L } from '../i18n/lang'

/**
 * Стиль общения меняет формулировки, но не содержание.
 *
 * Это сознательное ограничение: тон влияет на то, как сказано, и никогда —
 * на то, какие программы рекомендованы и как оценены шансы. Иначе выбор
 * «по-дружески» незаметно менял бы решение о будущем человека.
 */
type Variants = Record<ToneId, string>

function pick(tone: ToneId, v: Variants): string {
  return v[tone]
}

/** Обращение в начале разбора. */
export function greet(tone: ToneId, name: string): string {
  const who = name.trim()
  if (!who) {
    return pick(tone, {
      friendly: L('Смотри, что получилось.', 'Қара, не шықты.'),
      mentor: L('Разберём профиль по порядку.', 'Профильді ретімен талдайық.'),
      coach: L('Коротко о главном.', 'Ең бастысы туралы қысқаша.'),
      formal: L('Результат анализа профиля.', 'Профильді талдау нәтижесі.'),
    })
  }
  return pick(tone, {
    friendly: L(`${who}, смотри, что получилось.`, `${who}, қара, не шықты.`),
    mentor: L(`${who}, разберём твой профиль по порядку.`, `${who}, профиліңді ретімен талдайық.`),
    coach: L(`${who}, коротко о главном.`, `${who}, ең бастысы туралы қысқаша.`),
    formal: L(`Результат анализа профиля: ${who}.`, `Профильді талдау нәтижесі: ${who}.`),
  })
}

/** Подводка к следующему действию на экране плана. */
export function nudge(tone: ToneId): string {
  return pick(tone, {
    friendly: L('С этого проще всего начать', 'Осыдан бастаған оңай'),
    mentor: L('Логичный следующий шаг', 'Логикалық келесі қадам'),
    coach: L('Сделай это первым', 'Мұны бірінші жаса'),
    formal: L('Ближайшее действие', 'Жақын әрекет'),
  })
}

/** Комментарий к полноте анкеты. */
export function readinessPhrase(tone: ToneId, readiness: number): string {
  if (readiness >= 85) {
    return pick(tone, {
      friendly: L('Анкета подробная — рекомендации построены на полных данных.', 'Сауалнама толық — ұсыныстар толық деректерге негізделген.'),
      mentor: L('Профиль заполнен подробно, поэтому расчёт опирается на полный набор данных.', 'Профиль толық толтырылған, сондықтан есеп толық деректерге сүйенеді.'),
      coach: L('Данных хватает. Можно работать по плану.', 'Дерек жеткілікті. Жоспармен жұмыс істеуге болады.'),
      formal: L('Профиль заполнен полностью. Расчёт выполнен на полном наборе данных.', 'Профиль толық толтырылған. Есеп толық деректер жиынында орындалды.'),
    })
  }
  if (readiness >= 60) {
    return pick(tone, {
      friendly: L('Заполнено неплохо. Добавь баллы экзаменов — и оценка станет точнее.', 'Жақсы толтырылған. Емтихан балдарын қос — баға дәлірек болады.'),
      mentor: L('Данных достаточно для первого приближения. Баллы экзаменов сделают оценку точнее.', 'Дерек алғашқы жуықтауға жеткілікті. Емтихан балдары бағаны дәлдей түседі.'),
      coach: L('Почти всё есть. Добавь баллы — и подбор станет точнее.', 'Бәрі дерлік бар. Балдарды қос — таңдау дәлірек болады.'),
      formal: L('Данных достаточно. Для уточнения оценки укажите баллы экзаменов.', 'Дерек жеткілікті. Бағаны нақтылау үшін емтихан балдарын көрсетіңіз.'),
    })
  }
  return pick(tone, {
    friendly: L('Данных пока мало, поэтому подбор грубоватый. Вернись в анкету и уточни экзамены.', 'Дерек әзірге аз, сондықтан таңдау дөрекілеу. Сауалнамаға оралып, емтихандарды нақтыла.'),
    mentor: L('Данных мало, и это видно по точности: вернись в анкету и уточни экзамены и предметы.', 'Дерек аз, бұл дәлдіктен көрініп тұр: сауалнамаға оралып, емтихандар мен пәндерді нақтыла.'),
    coach: L('Мало данных. Заполни экзамены — подбор сразу станет полезнее.', 'Дерек аз. Емтихандарды толтыр — таңдау бірден пайдалы болады.'),
    formal: L('Объём данных недостаточен. Рекомендуется уточнить экзамены и профильные предметы.', 'Дерек көлемі жеткіліксіз. Емтихандар мен бейіндік пәндерді нақтылау ұсынылады.'),
  })
}
